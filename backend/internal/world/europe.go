// EuropeCommunes: every commune of Europe's cities (the update hides them while closed).
func EuropeCommunes() []string {
	var out []string
	for _, c := range europe {
		if slices.Contains(EuropeCountries, c.Country) {
			for _, cm := range c.Communes {
				out = append(out, cm.ID)
			}
		}
	}
	return out
}

