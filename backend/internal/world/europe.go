// roadLinked: whether a road joins two countries: the same one, or a chain of land borders between them. A country
// without borders listed (Africa's, the Americas') is joined to its land as before (SameLand).
func roadLinked(a, b string) bool {
	if a == b {
		return true
	}
	_, okA := Borders[a]
	_, okB := Borders[b]
	if !okA || !okB {
		return !okA && !okB
	}
	seen, next := map[string]bool{a: true}, []string{a}
	for len(next) > 0 {
		k := next[0]
		next = next[1:]
		for _, n := range Borders[k] {
			if n == b {
				return true
			}
			if !seen[n] {
				seen[n] = true
				next = append(next, n)
			}
		}
	}
	return false
}

// InEurope: whether a city is in Europe (its own diseases: no palu, sims/sante.go; its own streets).
func InEurope(cityID string) bool {
	c, ok := FindCity(cityID)
	return ok && CountryOf(c).Land == "europe"
}

